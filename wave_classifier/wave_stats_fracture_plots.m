% ==========================================================================
%  WAVE PARAMETER STATISTICS + BREAKUP ANALYSIS + WAVELENGTH RATIO ANALYSIS
%  Reads waves_class.csv (output of wave_classifier.m) and produces:
%
%  (1) STATISTICS TABLE
%      Prints min / max / mean / median of all key dimensionless parameters
%      (k, lambda, H/lambda, a/lambda, kH, kh, kLd, h/lambda, I_breakup),
%      split into ice and water subsets, with full context columns
%      (lambda, T_set, f_set, T_s, a, ka_set) for each statistic.
%      Rows with nearly zero amplitude (a_m ≈ 0) are removed before any computation.
%
%  (2) FOUR BREAKUP PLOTS
%      Shows the normalised breakup parameter I/I_br (Voermans et al. 2020,
%      threshold I_br = 0.014) with propagated uncertainty error bars:
%
%        Plot 1 — I/I_br vs ka_set  at a single fixed T_set  (user-set)
%        Plot 2 — I/I_br vs T_set   at a single fixed ka_set (user-set)
%        Plot 3 — I/I_br vs ka_set  sweeping all T_set  (colour-coded)
%        Plot 4 — I/I_br vs T_set   sweeping all ka_set (colour-coded)
%
%      Error bars are read from dI_breakup in the CSV
%
%  (3) TWO WAVELENGTH-RATIO PLOTS  (ice-modified vs. open-water wavelength)
%      Uses lambda_ratio_ice_over_setwater = lambda_m(ice) / lambda_open_water_set_m,
%      and its uncertainty d_lambda_ratio_ice_over_setwater, both read directly
%      from the CSV (computed once in wave_classifier.m — see that
%      script's header for exactly how each wavelength and the uncertainty
%      are derived;):
%
%        Plot 5 — lambda_ratio vs f_set   1 curve per set steepness (ka_set)
%        Plot 6 — lambda_ratio vs ka_set  1 curve per set frequency (f_set,
%                                          grouped via the corresponding T_set)
%
%      If waves_class.csv was generated by an older wave_classifier.m that
%      doesn't export these columns yet, a warning is printed and Plots 5-6
%      are skipped (re-run the updated wave_classifier.m to regenerate it).
%
%  USAGE
%      1. Run wave_classifier.m first to generate waves_class.csv.
%      2. Set csv_path, fixed_T_set, fixed_ka_set, save_path below.
%      3. Run this script.
%
%  BACKWARD COMPATIBILITY
%      If waves_class.csv was generated by wave_classifier v1 (missing
%      T_set or dI_breakup columns), a warning is printed and the script
%      falls back: T_set <- T_s (fixed-T filter approximate),
%      error bars suppressed. Same idea for the wavelength-ratio columns
%      (Section 3) — see above.
%
%  REFERENCES
%      Voermans et al. (2020). The Cryosphere, 14, 4265-4278.
% ==========================================================================
clear; clc; close all;

%% =========================================================================
% USER PARAMETERS
% =========================================================================

csv_path = 'waves_class.csv';

% ---- Breakup threshold ----
I_br_threshold = 0.014;   % Voermans et al.

% ---- Plot settings ----

tol_ka       = 0.005;     % Matching tolerance on ka_set
tol_T        = 0.01;      % Matching tolerance on T_set [s]

% ---- Export settings ----
save_fig   = true;
save_path  = 'E:\SIWWI2026\wave_classifier\';

% =========================================================================
% LOAD DATA
% =========================================================================

if ~isfile(csv_path)
    error('CSV file not found: %s', csv_path);
end

T = readtable(csv_path);

% ------------------------------------------------------------------
%  Backward-compatibility: if T_set column is absent (old CSV from
%  wave_classifier_v1), fall back to T_s so the script still runs,
%  but print a warning so the user knows to regenerate the CSV.
% ------------------------------------------------------------------
if ~ismember('T_set', T.Properties.VariableNames)
    warning(['Column T_set not found in CSV. ' ...
             'Re-run wave_classifier_v2 to regenerate waves_class.csv. ' ...
             'Falling back to T_s for now (fixed-T filter will be approximate).']);
    T.T_set = T.T_s;
end
% Backward-compatibility: dI_breakup absent in CSVs generated before this fix
if ~ismember('dI_breakup', T.Properties.VariableNames)
    warning('Column dI_breakup not found. Re-run wave_classifier_v2. Error bars will be suppressed.');
    T.dI_breakup = NaN(height(T), 1);
end

% Backward-compatibility: wavelength-ratio columns (Section 3 / Plots 5-6)
% absent in CSVs generated before this fix.
has_lambda_ratio_cols = all(ismember( ...
    {'f_set_Hz','lambda_open_water_set_m', ...
     'lambda_ratio_ice_over_setwater','d_lambda_ratio_ice_over_setwater'}, ...
    T.Properties.VariableNames));
if ~has_lambda_ratio_cols
    warning(['Wavelength-ratio columns not found in CSV. ' ...
             'Re-run the updated wave_classifier.m to regenerate waves_class.csv. ' ...
             'Plots 5-6 will be skipped.']);
end

% =========================================================================
% Remove artefact rows (a_m ≈ 0)
% =========================================================================

N_before = height(T);
T = T(T.a_m > 1e-10, :);
N_after  = height(T);

fprintf('Loaded %d rows  ->  %d artefact row(s) removed  ->  %d rows retained.\n\n', ...
    N_before, N_before - N_after, N_after);

% =========================================================================
% Subsets
% =========================================================================

T_ice   = T(T.Has_Ice == 1, :);
T_water = T(T.Has_Ice == 0, :);

fprintf('ICE rows  : %d\n', height(T_ice));
fprintf('WATER rows: %d\n\n', height(T_water));

% =========================================================================
% STATISTICS 
% =========================================================================
%
%  Each COLS entry: {column_name, display_label, ice_only_flag}
% =========================================================================

COLS = {
    'k_rad_m',             'k  [rad/m]',                           false;
    'lambda_m',            'lambda  [m]',                          false;
    'H_over_lambda',       'H/lambda  (water depth / lambda)',     false;
    'H_over_lambda_water', 'H/lambda_water  (= H/lambda, alias)',  false;
    'a_over_lambda',       'a/lambda',                             false;
    'kH',                  'kH',                                   false;
    'kh',                  'kh  (ice thickness * k)',              true;
    'kLd',                 'kLd  (k * elastic length)',            true;
    'h_over_lambda',       'h/lambda  (ice thickness / lambda)',   true;
    'I_breakup',           'I_breakup',                            true;
};

for s = 1:size(COLS,1)

    col      = COLS{s,1};
    display  = COLS{s,2};
    ice_only = COLS{s,3};

    fprintf('%s\n', repmat('=',1,90));
    fprintf('  %s\n', display);
    fprintf('%s\n', repmat('=',1,90));

    if ice_only
        fprintf('  >> ICE only <<\n');
        report_col(col, T_ice);
    else
        fprintf('  [ ICE ]\n');
        report_col(col, T_ice);
        fprintf('  [ WATER ]\n');
        report_col(col, T_water);
    end
end

fprintf('%s\n', repmat('=',1,90));
fprintf('Done with statistics.\n\n');

%% =========================================================================
% BREAKUP PLOTTING SECTION
% =========================================================================
df = T;
filename_3 = 'I_vs_ka_fixed_T';
filename_4 = 'I_vs_T_fixed_ka';


% Keep only ice cases

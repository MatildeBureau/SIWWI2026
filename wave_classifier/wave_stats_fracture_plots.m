function report_col(col, subset)

    vals  = subset.(col);
    valid = ~isnan(vals);

    if ~any(valid)
        fprintf('  [no data]\n\n');
        return
    end

    vals_valid = vals(valid);
    sub_valid  = subset(valid, :);

    stat_names = {'min','max','mean','median'};
    stat_vals  = [min(vals_valid), max(vals_valid), ...
                  mean(vals_valid), median(vals_valid)];

    for s = 1:4

        stat = stat_names{s};
        val  = stat_vals(s);

        if s <= 2
            if s == 1, [~,idx] = min(vals_valid);
            else,      [~,idx] = max(vals_valid); end
            row = sub_valid(idx, :);
            ctx = context_str(row, col, false);
        else
            [~,idx] = min(abs(sub_valid.(col) - val));
            row = sub_valid(idx, :);
            ctx = context_str(row, col, true);
        end

        fprintf('    %-7s %14.6g     %s\n', stat, val, ctx);
    end

    fprintf('\n');
end


function str = context_str(row, col, is_nearest)

    parts = {};

    if ~strcmp(col,'lambda_m')
        parts{end+1} = sprintf('lambda=%.4f m', row.lambda_m);
    end

    % Report both set period and measured period for clarity
    T_set_val = row.T_set;
    T_s_val   = row.T_s;
    f_set_val = 1 / T_set_val;

    parts{end+1} = sprintf('T_set=%.4f s  f_set=%.4f Hz', T_set_val, f_set_val);
    parts{end+1} = sprintf('T_s=%.4f s', T_s_val);
    parts{end+1} = sprintf('a=%.5g m', row.a_m);
    parts{end+1} = sprintf('ka_set=%.4f', row.ka_set);

    str = strjoin(parts, '  |  ');

    if is_nearest
        str = [str '  [nearest row]'];
    end
end